"""One generate run — the entry point the CLI and the App share (post60).

``codegen generate`` (``cli._run_pairs``) and the App's live run
(``ui.backend.demo.DemoRunner._work``) both drive a :class:`GenerateRun`:

- the run-level lines (the environment's QUESTIONs, the run's INPUT_NEEDED),
  each held-back feed's lines and each value no document states;
- every feed through :meth:`GenerateRun.feed` — the BSA's choices
  (codegen.input_choices), the feed's own owed inputs and LOB question,
  CRASHED (partial emit files removed) / GATE_FAIL (files kept under
  ``quarantine/`` + GATE_FAIL.md) / written;
- :meth:`GenerateRun.finish` — the outcome (``run_stages.generate_outcome``),
  the exit code and ``<out root>/CODEGEN_STAGES.json``;
- post76: :meth:`GenerateRun.layer2` — the Layer-2 stage over the feeds whose
  files were written (codegen.layer2_stage), AFTER the outcome: one request
  per feed, its ``layer2`` block added to the manifest.

So the manifest — ``questions`` with ``blocking``, each feed's ``written``,
``open``, ``inputs`` and ``iig_cells``, the outcome — is built by the same code
from both, and the App's run state reads outcome and ``written`` from it
(``read_stage_manifest``) instead of inferring them. Only the console differs:
the CLI passes ``say=print`` and its FAIL / CODEGEN-ERROR reporter, the App a
stage logger. The feed itself is generated by the caller's ``produce`` —
both are ``cli.generate_feed_result`` (the App wraps it in its FeedRun)."""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path
from typing import Any

from codegen import run_stages
from codegen.run_errors import Coord


class GenerateRun:
    """The bookkeeping of one generate run (see the module docstring)."""

    def __init__(self, config, *, out_root: Path, command: str = "generate",
                 output_mode=None, iig_template: str | None = None,
                 conventions_profile: str | None = None, inputs: dict | None = None,
                 choices: dict | None = None, base: Path | None = None,
                 say: Callable[[str], None] = print,
                 fail: Callable[..., None] | None = None,
                 report: Callable[..., None] | None = None) -> None:
        self.config = config
        self.out_root = Path(out_root)
        self.command = command
        self.output_mode = output_mode
        self.iig_template = iig_template
        self.conventions_profile = conventions_profile
        self.inputs = dict(inputs or {})
        self.choices = dict(choices or {})
        self.base = base if base is not None else Path(".")
        self.say = say
        self._fail = fail
        self._report = report
        self.open_items: list[dict] = []        # the manifest's questions
        self.template_items: list = []          # answers_template.yaml
        self.owed: list = []                    # OwedInput, the App's banner
        self.feed_entries: list[dict] = []
        self.entry_of: dict[str, dict] = {}
        self.records: dict[str, dict] = {}
        self.results: dict[str, Any] = {}       # feed_id -> produce()'s result
        self.errors: dict[str, str] = {}        # feed_id -> the error (App: kept going)
        self.kept: dict[str, list[Path]] = {stage: [] for stage in run_stages.EMIT_STAGES}
        self.quarantined: list[str] = []
        self.crashed = self.gate_failed = self.hard_failed = False
        self.matched_feed = False
        self.layer2_jobs: list = []             # post76: the stage's work, feed by feed
        self.layer2_block: dict | None = None

    # -- lines before any feed ---------------------------------------------------

    def run_level(self, questions: list[tuple[str, str]], items: list) -> None:
        """The run-level QUESTIONs (a required environment value) and
        INPUT_NEEDED items (codegen.owed_inputs.OwedInput, scope run)."""
        from codegen.layout.answers_template import TemplateItem
        from codegen.owed_inputs import INPUTS_SECTION

        self.open_items += [run_stages.open_item("QUESTION", key) for key, _r in questions]
        # post61: an applied profile default is shown, never open
        self.open_items += [run_stages.open_item("INPUT_NEEDED", i.key) for i in items
                            if i.is_open]
        self.owed += items
        self.template_items += [TemplateItem(key, reason, [], INPUTS_SECTION)
                                for key, reason in questions]
        self.template_items += [TemplateItem(
            i.key, i.question,
            list(self.config.environments) if i.key == "run.environment" else [],
            INPUTS_SECTION, options=list(i.options), proposed=i.proposed,
            proposed_template=i.template, applied=i.applied) for i in items]

    def unstated(self, questions: list) -> None:
        """post57: each value NO document states — a QUESTION (blocking)."""
        from codegen.cli import answer_line
        from codegen.layout.answers_template import TemplateItem

        for question in questions:
            self.say(answer_line("QUESTION", question.key, question.reason))
        self.template_items += [TemplateItem(q.key, q.reason, [], "gaps") for q in questions]
        self.open_items += [run_stages.open_item("QUESTION", q.key, feed=q.feed_id)
                            for q in questions]
        if questions:
            self.matched_feed = True

    def held_back(self, pending: list) -> None:
        """Each held-back feed's lines (QUESTION / UNRESOLVED, blocking)."""
        from codegen.cli import _pending_feed, _pending_key, _pending_label

        self.open_items += [run_stages.open_item(_pending_label(p), _pending_key(p),
                                                 feed=_pending_feed(p, self.config))
                            for p in pending]

    def hard_fail(self) -> None:
        """A failure before anything is written (a mismatch, no --feed match)."""
        self.hard_failed = True

    @property
    def failed(self) -> bool:
        return self.crashed or self.gate_failed or self.hard_failed

    # -- one feed ------------------------------------------------------------------

    def feed(self, spec, feed_no: int, of: int, *, frd_path: Path | None,
             produce: Callable[[dict], Any], reraise: bool = True) -> Any:
        """Generate ``spec`` through ``produce(faq_answers)`` (its result has a
        ``gate``, or is the GateResult) and record it. ``reraise``: an uncaught
        error propagates after the manifest says CRASHED (the CLI); else it is
        kept in :attr:`errors` and the run goes on (the App)."""
        from codegen import input_choices as choices_mod
        from codegen import owed_inputs as owed_mod
        from codegen.cli import _input_choices, _key_question, _lob_question
        from codegen.emit.context import TemplateGapError
        from codegen.faq import faq_for_spec, with_faq_answers

        self.matched_feed = True
        config = self.config
        index = owed_mod.frd_feed_index(frd_path, spec.feed_id, config)
        resolved = _input_choices(spec, config, self.inputs, self.choices, index,
                                  self.output_mode, self.iig_template, self.conventions_profile,
                                  base=self.base)
        self.records[spec.feed_id] = choices_mod.records(resolved)
        faq_answers = {**owed_mod.answers_for(self.inputs, index, spec.feed_id),
                       **choices_mod.faq_answers(resolved)}
        feed_dir = self.out_root / spec.feed_slug
        run_stages.clear_quarantine(feed_dir)
        before = run_stages.snapshot(feed_dir)
        where = Coord("feed", n=feed_no, of=of)
        try:
            result = produce(faq_answers)
            gate = getattr(result, "gate", result)
            owed = owed_mod.owed_inputs(
                spec, config, index=index, output_mode=self.output_mode,
                iig_template=self.iig_template,
                faq=with_faq_answers(faq_for_spec(spec, config, base_dir=self.base),
                                     faq_answers),
                resolved=resolved, profile=config.conventions.get(self.conventions_profile))
            for item in owed:
                self.say(owed_mod.input_line(item))
            self.owed += owed
            self.template_items += owed_mod.template_items(owed)
            self.template_items += choices_mod.shared_template_items(spec.feed_id, owed)
            self.open_items += [run_stages.open_item("INPUT_NEEDED", item.key, feed=spec.feed_id)
                                for item in owed if item.is_open]
            # 2026-10-14 (D1 pair_12): ONE blocking question for the feed whose
            # files the LOB lookup keyed to no single LOB (its LOB cells open)
            lob_item = _lob_question(spec, say=self.say)
            if lob_item is not None:
                self.template_items.append(lob_item)
                self.open_items.append(run_stages.open_item("QUESTION", lob_item.key,
                                                            feed=spec.feed_id))
            # post70: a merge load with no key signal — ONE blocking question
            key_item = _key_question(
                spec, config, with_faq_answers(faq_for_spec(spec, config, base_dir=self.base),
                                               faq_answers),
                self.output_mode, self.iig_template, self.conventions_profile, say=self.say)
            if key_item is not None:
                self.template_items.append(key_item)
                self.open_items.append(run_stages.open_item("QUESTION", key_item.key,
                                                            feed=spec.feed_id))
            self._landing_input(spec, index)
            self._notebook_environment(spec, index)
        except TemplateGapError as exc:
            if self._fail is not None:
                self._fail(self.command, f"{spec.feed_id} — template gap: {exc}",
                           "template.gap", where, exc=exc)
            self.crashed = True
            self.errors[spec.feed_id] = f"{type(exc).__name__}: {exc}"
            removed = run_stages.remove_partial(feed_dir, before)
            self.feed_entries.append(run_stages.feed_entry(
                self.out_root, feed_no, of, "CRASHED", {}, removed))
            return None
        except Exception as exc:
            # CRASHED: an uncaught error mid-feed — no partial workbook survives
            removed = run_stages.remove_partial(feed_dir, before)
            self.feed_entries.append(run_stages.feed_entry(
                self.out_root, feed_no, of, "CRASHED", {}, removed))
            self.crashed = True
            if reraise:
                run_stages.write_stage_manifest(
                    self.out_root, command=self.command, exit_code=1,
                    statuses=run_stages.stage_statuses("CRASHED", self.kept),
                    feeds=self.feed_entries, questions=self.open_items)
                raise
            self.errors[spec.feed_id] = f"{type(exc).__name__}: {exc}"
            return None
        self.results[spec.feed_id] = result
        withheld, nothing_written = self._withhold_notebook(spec, feed_dir, before)
        if gate.verdict == "FAIL":
            self._gate_fail(spec, gate, feed_no, of, feed_dir, before, where)
            return result
        written = run_stages.written_since(feed_dir, before)
        for stage, paths in written.items():
            self.kept[stage] += paths
        self.feed_entries.append(run_stages.feed_entry(
            self.out_root, feed_no, of, gate.verdict, written, iig_cells=gate.iig_cells,
            withheld=withheld, nothing_written=nothing_written))
        self.entry_of[spec.feed_id] = self.feed_entries[-1]
        self.keep_layer2(spec, getattr(result, "layer2_job", None), feed_no, of)
        return result

    def keep_layer2(self, spec, job, feed_no: int, of: int) -> None:
        """post76: a written feed's Layer 2 waits for the run's outcome; a
        GATE_FAIL / CRASHED feed's, or one that wrote nothing, is not asked.
        (The App passes its job here: its FeedRun does not carry one.)"""
        entry = self.entry_of.get(spec.feed_id)
        if job is None or entry is None or not entry.get("written") or (
                entry.get("status") == "GATE_FAIL"):
            return
        job.n, job.of, job.out_root = feed_no, of, self.out_root
        self.layer2_jobs.append(job)

    def _landing_input(self, spec, index) -> None:
        """post74 (D1 post73 pair_11): a landing no document states leaves the
        IIG's path cells open - ONE input per feed under the IIG cell's key
        (codegen.metadata_template.landing_question), the convention shown as
        the proposal. Non-blocking here; a notebook run makes it blocking."""
        from codegen.cli import answer_line
        from codegen.layout.answers_template import TemplateItem
        from codegen.metadata_template import landing_question
        from codegen.owed_inputs import INPUTS_SECTION, _template

        asked = landing_question(_template(self.config, self.output_mode, self.iig_template),
                                 spec, index)
        if asked is None or any(i["key"] == asked[0] for i in self.open_items):
            return
        key, reason, proposal = asked
        self.say(answer_line("INPUT_NEEDED", key, reason))
        self.open_items.append(run_stages.open_item("INPUT_NEEDED", key, feed=spec.feed_id))
        self.template_items.append(TemplateItem(key, reason, [], INPUTS_SECTION,
                                                proposed=proposal))

    def _notebook_environment(self, spec, index=None) -> None:
        """post68: a value the notebook needs from the environment (a catalog,
        the storage account, a container) or the documents (the landing) and
        does not have is a QUESTION — blocking, so the notebook is withheld
        (codegen.emit.notebook_env). Notebook runs only."""
        from codegen.cli import answer_line
        from codegen.emit.notebook_env import notebook_environment
        from codegen.layout.answers_template import TemplateItem
        from codegen.output_modes import output_parts
        from codegen.owed_inputs import INPUTS_SECTION

        if "notebook" not in output_parts(self.output_mode or self.config.output.mode):
            return
        for item in notebook_environment(spec, self.config, self.iig_template,
                                         index).missing:
            same = [i for i in self.open_items if i["key"] == item.key]
            if any(i["blocking"] for i in same):
                continue
            self.say(answer_line("QUESTION", item.key, item.reason))
            if same:
                # an INPUT_NEEDED (the workbook's cells open) the notebook cannot run
                # without: blocking on a notebook run
                for open_line in same:
                    open_line.update(line="QUESTION", blocking=True)
                continue
            self.open_items.append(run_stages.open_item(
                "QUESTION", item.key, feed=None if item.run_scope else spec.feed_id))
            self.template_items.append(TemplateItem(item.key, item.reason, [], INPUTS_SECTION))

    def blocking_for(self, feed_id: str) -> list[dict]:
        """The blocking lines open for ``feed_id``: its own and the run-level ones."""
        return [i for i in self.open_items if i["blocking"]
                and (i["scope"] == "run" or i.get("feed") == feed_id)]

    def _withhold_notebook(self, spec, feed_dir: Path, before) -> tuple[int, bool]:
        """post68: a feed with a blocking line open writes no notebook (the
        workbook is still written for review, post58). A notebook-only run
        then keeps none of its emit artefacts either: ``written: false``.
        (files removed, nothing written)."""
        from codegen.cli import answer_line
        from codegen.output_modes import output_parts

        parts = output_parts(self.output_mode or self.config.output.mode)
        blocking = self.blocking_for(spec.feed_id) if "notebook" in parts else []
        if not blocking:
            return 0, False
        notebook_only = "framework" not in parts
        removed = run_stages.remove_notebook(feed_dir, before, emit_too=notebook_only)
        keys = ", ".join(dict.fromkeys(i["key"] for i in blocking))
        self.say(answer_line("NOTE", f"feeds.{spec.feed_id}.notebook",
                             f"not written — {len(blocking)} blocking line(s) open ({keys}); "
                             "answer them and re-run"))
        return removed, notebook_only

    def _gate_fail(self, spec, gate, feed_no, of, feed_dir, before, where) -> None:
        """GATE_FAIL: complete artefacts, the gate said no — kept for review."""
        self.gate_failed = True
        failing = [c for c in gate.checks if not c.passed and not c.not_run]
        # D1 post51 pair_01: counts per flag type and per violated rule
        # (vocabulary only) for the coordinates tier
        flag_counts = run_stages.flag_counts(gate.flags)
        violations: dict[str, int] = {}
        for check in failing:
            for kind, n in check.violations.items():
                violations[kind] = violations.get(kind, 0) + n
        if self._report is not None:
            self._report(self.command, "gate.verdict_fail", where,
                         checks=[c.name for c in failing], flags=flag_counts,
                         violations=violations)
        for kind, n in sorted(flag_counts.items(), key=lambda kv: (-kv[1], kv[0])):
            self.say(f"{'GATE_FLAGS':<15} {kind} — {n}")
        moved = run_stages.quarantine(feed_dir, before)
        q_dir = feed_dir / run_stages.QUARANTINE_DIR
        q_dir.mkdir(parents=True, exist_ok=True)
        (q_dir / run_stages.GATE_FAIL_FILE).write_text(
            run_stages.gate_fail_note(gate, feed_no, of, len(moved)),
            encoding="utf-8", newline="\n")
        written = run_stages.by_stage(moved)
        for stage, paths in written.items():
            self.kept[stage] += paths
        self.quarantined.append(q_dir.relative_to(self.out_root).as_posix())
        self.feed_entries.append(run_stages.feed_entry(
            self.out_root, feed_no, of, "GATE_FAIL", written, quarantine_dir=q_dir,
            iig_cells=gate.iig_cells))
        self.entry_of[spec.feed_id] = self.feed_entries[-1]
        self.say(f"{'GATE_FAIL':<15} {spec.feed_id} — {run_stages.REVIEW_ONLY}: "
                 f"{len(moved)} file(s) moved to {q_dir} ({run_stages.GATE_FAIL_FILE})")

    # -- the end -------------------------------------------------------------------

    def review_open(self, feed_id: str) -> dict[str, int]:
        """post66: the open lines a feed's IIG review faces — its own plus the
        run-level ones (they leave cells open in every feed's IIG):
        ``{"open": n, "blocking": n}``."""
        counts = run_stages.open_counts(
            [i for i in self.open_items if i.get("scope") == "run" or i.get("feed") == feed_id])
        return {"open": counts["blocking"] + counts["non_blocking"],
                "blocking": counts["blocking"]}

    def finish(self, *, template_path: Path | None = None) -> tuple[str, int]:
        """The outcome and the exit code; the manifest written (and the answers
        template, when ``template_path`` is given)."""
        if template_path is not None:
            from codegen.cli import _write_template

            _write_template(template_path, self.template_items, "generate", merge=True)
        outcome = run_stages.generate_outcome(
            crashed=self.crashed, hard_failed=self.hard_failed, gate_failed=self.gate_failed,
            open_items=self.open_items)
        code = 1 if self.failed else 3 if outcome == "NEEDS_ANSWERS" else 0
        for feed_id, entry in self.entry_of.items():
            entry["open"] = run_stages.open_counts(
                [i for i in self.open_items if i.get("feed") == feed_id])
            if self.records.get(feed_id):
                entry["inputs"] = self.records[feed_id]
        statuses = run_stages.stage_statuses(outcome, self.kept, self.quarantined)
        for stage in run_stages.EMIT_STAGES:
            if outcome in ("CRASHED", "FAIL"):
                self.say(f"{'SKIPPED':<15} {stage} — {run_stages.SKIPPED_UPSTREAM} (exit code "
                         "unchanged; a crashed feed's partial emit artefacts are removed)")
        counts = run_stages.open_counts(self.open_items)
        if outcome == "PASS_WITH_OPEN_INPUTS":
            self.say(f"{'OUTCOME':<15} generate — PASS_WITH_OPEN_INPUTS: {len(self.entry_of)} "
                     f"feed(s) written; {counts['non_blocking']} input(s) still open, none "
                     "blocking (answers_template.yaml); exit 0")
        elif outcome == "NEEDS_ANSWERS":
            self.say(f"{'OUTCOME':<15} generate — NEEDS_ANSWERS: {counts['blocking']} blocking "
                     f"question(s) open, {counts['non_blocking']} input(s); "
                     f"{len(self.entry_of)} feed(s) written for review, not deployable until "
                     "answered (CODEGEN_STAGES.json written: true); exit 3")
        run_stages.write_stage_manifest(self.out_root, command=self.command, exit_code=code,
                                        statuses=statuses, feeds=self.feed_entries,
                                        questions=self.open_items)
        return outcome, code

    def layer2(self, mode: str, *, dry_run: bool, build=None, console: bool = True) -> dict:
        """post76: the Layer-2 stage — after :meth:`finish` (the outcome, the files
        and the manifest are written first). ``mode`` = now | defer | skip; the
        manifest gains its ``layer2`` block; the exit code is not touched.
        Returns {feed_id: (candidates, usage)}."""
        from codegen.layer2_stage import run_stage

        if self.layer2_jobs and console:
            rules = sum(job.rules for job in self.layer2_jobs)
            self.say(f"{'STAGE':<15} layer2 — {mode}: {rules} unmapped rule(s) over "
                     f"{len(self.layer2_jobs)} feed(s), one request per feed with rules "
                     "(after the outcome; never changes it)")
        self.layer2_block, results = run_stage(
            self.layer2_jobs, mode, config=self.config, dry_run=dry_run, base_dir=self.base,
            out_root=self.out_root, say=self.say, console=console, build=build)
        return results


def run_level_lines(config, inputs: dict, *, output_mode, iig_template, choices=None
                    ) -> tuple[list[tuple[str, str]], list]:
    """(the environment's required-key QUESTIONs, the run-level INPUT_NEEDED
    items) — the same for the CLI and the App."""
    from codegen import environments as envs
    from codegen import owed_inputs as owed_mod

    # post68: one required-environment check whatever the output mode (the
    # notebook reads the environment too); none when no environment is defined
    questions = envs.required_items(config)
    items = [*owed_mod.environment_inputs(config, output_mode=output_mode,
                                          iig_template=iig_template),
             *owed_mod.run_owed_inputs(config, inputs, output_mode=output_mode,
                                       iig_template=iig_template, choices=choices)]
    return questions, items


__all__ = ["GenerateRun", "run_level_lines"]
